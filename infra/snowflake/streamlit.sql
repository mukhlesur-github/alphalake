-- Streamlit in Snowflake (warehouse runtime) for AlphaLake: one app per persona, because warehouse-runtime apps
-- run with their OWNER's role. Run as ACCOUNTADMIN after uploading app/ + src/alphalake/ to @ALPHALAKE.APP.CODE.
USE ROLE ACCOUNTADMIN;
CREATE SCHEMA IF NOT EXISTS ALPHALAKE.APP COMMENT = 'Streamlit in Snowflake apps (one per persona)';
CREATE STAGE IF NOT EXISTS ALPHALAKE.APP.CODE ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE') DIRECTORY = (ENABLE = TRUE);

GRANT USAGE ON SCHEMA ALPHALAKE.APP TO ROLE ALPHALAKE_PM;
GRANT USAGE ON SCHEMA ALPHALAKE.APP TO ROLE ALPHALAKE_ANALYST;
GRANT CREATE STREAMLIT ON SCHEMA ALPHALAKE.APP TO ROLE ALPHALAKE_PM;
GRANT CREATE STREAMLIT ON SCHEMA ALPHALAKE.APP TO ROLE ALPHALAKE_ANALYST;
GRANT READ ON STAGE ALPHALAKE.APP.CODE TO ROLE ALPHALAKE_PM;
GRANT READ ON STAGE ALPHALAKE.APP.CODE TO ROLE ALPHALAKE_ANALYST;

-- Each app is created BY its persona role, so it runs as that role.
USE ROLE ALPHALAKE_PM;
CREATE OR REPLACE STREAMLIT ALPHALAKE.APP.ALPHALAKE_PM
  FROM '@ALPHALAKE.APP.CODE' MAIN_FILE = 'streamlit_app.py'
  QUERY_WAREHOUSE = ALPHALAKE_WH_APP TITLE = 'AlphaLake (PM)';
USE ROLE ALPHALAKE_ANALYST;
CREATE OR REPLACE STREAMLIT ALPHALAKE.APP.ALPHALAKE_ANALYST
  FROM '@ALPHALAKE.APP.CODE' MAIN_FILE = 'streamlit_app.py'
  QUERY_WAREHOUSE = ALPHALAKE_WH_APP TITLE = 'AlphaLake (Analyst)';
USE ROLE ACCOUNTADMIN;

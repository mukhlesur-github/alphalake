-- Where is my data? Row counts per layer + pipe status.
SELECT 'BRONZE.SECURITIES_RAW' t, COUNT(*) n FROM ALPHALAKE.BRONZE.SECURITIES_RAW
UNION ALL SELECT 'BRONZE.PRICES_RAW', COUNT(*) FROM ALPHALAKE.BRONZE.PRICES_RAW
UNION ALL SELECT 'BRONZE.HOLDINGS_RAW', COUNT(*) FROM ALPHALAKE.BRONZE.HOLDINGS_RAW
UNION ALL SELECT 'BRONZE.TRADE_EVENTS_RAW', COUNT(*) FROM ALPHALAKE.BRONZE.TRADE_EVENTS_RAW
UNION ALL SELECT 'BRONZE.DOC_PARSED_RAW', COUNT(*) FROM ALPHALAKE.BRONZE.DOC_PARSED_RAW
UNION ALL SELECT 'SILVER.TRADE_EVENTS', COUNT(*) FROM ALPHALAKE.SILVER.TRADE_EVENTS
UNION ALL SELECT 'SILVER.TRADES_CURRENT', COUNT(*) FROM ALPHALAKE.SILVER.TRADES_CURRENT
UNION ALL SELECT 'SILVER.QUARANTINE_TRADE_EVENTS', COUNT(*) FROM ALPHALAKE.SILVER.QUARANTINE_TRADE_EVENTS
UNION ALL SELECT 'GOLD.DIM_SECURITY', COUNT(*) FROM ALPHALAKE.GOLD.DIM_SECURITY
UNION ALL SELECT 'DOCS.DOC_CHUNKS', COUNT(*) FROM ALPHALAKE.DOCS.DOC_CHUNKS;
SELECT SYSTEM$PIPE_STATUS('ALPHALAKE.BRONZE.PIPE_TRADE_EVENTS') AS trade_pipe_status;
